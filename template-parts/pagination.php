<?php
/**
 * Numbered pagination for the main query. Previous and Next words come from Theme Settings.
 *
 * @package Armodafinil_Australia
 */

global $wp_query;
if ( $wp_query->max_num_pages < 2 ) {
	return;
}
$links = paginate_links( array(
	'type'      => 'array',
	'prev_text' => armo_label( 'label_previous' ) ?: '&lsaquo;',
	'next_text' => armo_label( 'label_next' ) ?: '&rsaquo;',
	'mid_size'  => 1,
) );
if ( empty( $links ) ) {
	return;
}
?>
<nav class="mt-12 flex flex-wrap items-center justify-center gap-2" aria-label="<?php echo esc_attr( armo_label( 'label_next' ) ?: get_bloginfo( 'name' ) ); ?>">
	<?php foreach ( $links as $link ) : ?>
		<?php
		$is_current = false !== strpos( $link, 'current' );
		$link       = str_replace( 'page-numbers', 'inline-flex h-10 min-w-10 items-center justify-center rounded-lg border px-3 text-sm font-semibold ' . ( $is_current ? 'border-primary bg-primary text-white' : 'border-border bg-white text-primary hover:bg-secondary' ), $link );
		echo $link; // phpcs:ignore WordPress.Security.EscapeOutput -- generated by paginate_links().
		?>
	<?php endforeach; ?>
</nav>
